export const photoByUrl = url => BUILTIN_PHOTO_PRESETS.find(x=>x.url===url)||null;
export const photoFor = (category,subcategory,itemName='') => {
 const exact=BUILTIN_PHOTO_PRESETS.find(x=>x.cat===category&&x.sub===subcategory);
 if(exact)return exact;
 // Category fallback is *illustrative* and always visibly labeled.
 if(category==='Cakes')return BUILTIN_PHOTO_PRESETS.find(x=>x.cat==='Cakes');
 if(category==='Cookies')return BUILTIN_PHOTO_PRESETS.find(x=>x.cat==='Cookies');
 if(category==='Pies')return BUILTIN_PHOTO_PRESETS.find(x=>x.cat==='Pies');
 if(category==='Cheesecakes')return BUILTIN_PHOTO_PRESETS.find(x=>x.cat==='Cheesecakes');
 if(category==='Pastries')return BUILTIN_PHOTO_PRESETS.find(x=>x.cat==='Pastries');
 if(category==='Bars & Brownies')return BUILTIN_PHOTO_PRESETS.find(x=>x.cat==='Bars & Brownies');
 return null;
};
